"""Rutas HTTP de socio - Conecta cada endpoint directamente con controllers.socio_controller."""
from fastapi import APIRouter
from controllers import socio_controller

router = APIRouter(prefix="/socio", tags=["Socios"])

router.post("/register")(socio_controller.register_socio)
router.post("/conductor/register")(socio_controller.register_socio_conductor)
router.get("/conductor/profile")(socio_controller.get_socio_conductor_profile)
router.post("/conductor/go-online")(socio_controller.socio_conductor_go_online)
router.post("/conductor/go-offline")(socio_controller.socio_conductor_go_offline)
router.post("/conductor/update-location")(socio_controller.update_conductor_location)
router.get("/conductor/nearby")(socio_controller.get_nearby_conductors)
router.post("/repartidor/register")(socio_controller.register_socio_repartidor)
router.get("/repartidor/profile")(socio_controller.get_socio_repartidor_profile)
router.post("/repartidor/go-online")(socio_controller.socio_repartidor_go_online)
router.post("/repartidor/go-offline")(socio_controller.socio_repartidor_go_offline)
router.get("/repartidor/nearby")(socio_controller.get_nearby_repartidores)
router.post("/comercial/register")(socio_controller.register_socio_comercial)
router.get("/comercial/profile")(socio_controller.get_socio_comercial_profile)
router.post("/comercial/products")(socio_controller.create_product)
router.get("/comercial/products")(socio_controller.get_comercial_products)
router.put("/comercial/products/{product_id}")(socio_controller.update_product)
router.delete("/comercial/products/{product_id}")(socio_controller.delete_product)
router.get("/comercial/orders")(socio_controller.get_comercial_orders)
router.patch("/comercial/orders/{order_id}")(socio_controller.update_order_status)
router.post("/repartidor/delivery/toggle")(socio_controller.toggle_delivery_mode)
router.get("/repartidor/delivery/status")(socio_controller.get_delivery_status)
router.post("/conductor/delivery/toggle")(socio_controller.toggle_conductor_delivery_mode)
router.get("/conductor/delivery/status")(socio_controller.get_conductor_delivery_status)
